                        cross = np.empty((len(other), len(tags), len(vx), K), dtype=np.uint16)
                        for io, ot in enumerate(other):
                            for ic, tagc in enumerate(tags):
                                th = thr_all[(ot, tagc)]; cross[io, ic] = T.counts_below(Ps, np.stack([np.broadcast_to(th[f"{fr}|{v}|{cb['alpha']}"], (K,)) for v in vx]))
