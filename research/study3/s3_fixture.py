    sp = R.spec_of(grid, False); man = json.loads((ROOT / R.TOKENS_MANIFEST).read_text()); man_sha = sha(ROOT / R.TOKENS_MANIFEST)
    inputs = json.loads((ROOT / R.INPUTS).read_text()); keys_e = list(range(grid["key_eval_start"], grid["key_eval_start"] + grid["K"]))
    K, K_fit = sp["K"], sp["K_fit"]; N_C = sp["N_cal_set"]; alphas = list(grid["alpha"]); ia01 = alphas.index(0.01); beta, delta = grid["beta"], grid["delta"]
    toks = list(sp["toks"]); tags = list(sp["cells"]); vs = R.variant_names(sp["N_cal"]); vx = R.cross_variant_names(grid); cb = grid["cal_bootstrap"]; cbg = grid["crossed_bootstrap"]
    rng0 = np.random.default_rng(seed); t_all = time.time(); n_written = 0
    eval_sha = {(tok, tag): R.eval_tokens_sha(SD.load_eval(tag, tok, man)) for tok in toks for tag in tags}   # the registered evaluation digests (key-free)
    for h in sp["h"]:
        # the synthetic key shifts: per (family, rule, tokenizer) one draw of K + K_fit shift vectors over the 20 sets (the fitting keys only use the calibration sets)
        D = {}
        for fam in R.FAMILIES:
            for rule in grid["rules"]:
                blk = inputs["blocks"][f"h{h}|{rule}"]
                for tok in toks:
                    S = shift_cov(blk, tok, tags); w, V = np.linalg.eigh(S); Lm = V * np.sqrt(np.clip(w, 0, None))
                    D[(fam, rule, tok)] = rng0.standard_normal((K + K_fit, 2 * len(tags))) @ Lm.T
        thr_all = {}; thr_dig = {}
        for tok in toks:
            for tag in tags:
                i = tags.index(tag); name = R.unit_name("cal", tok, tag, h); rng = np.random.default_rng([int(hashlib.sha256(name.encode()).hexdigest()[:8], 16), seed])
                arrays = {}; summ = {}; t0 = time.time()
                for fam in R.FAMILIES:
                    for rule in grid["rules"]:
                        fr = f"{fam}|{rule}"; blk = inputs["blocks"][f"h{h}|{rule}"]; sC = np.sqrt(max(blk["sets"][f"{tok}|{tag}|C5000"]["sigma2"], 1e-12))
                        dC = D[(fam, rule, tok)][:, len(tags) + i]
                        Pe = norm.sf(dC[None, :K] + sC * rng.standard_normal((N_C, K))); Pf = norm.sf(dC[None, K:] + sC * rng.standard_normal((N_C, K_fit)))
                        summ[fr] = {"scheme": {}, "per_key_z": {}}
                        for al in alphas:
                            thr = T.per_key_thresholds(Pe, al, sp["N_cal"], delta)
                            for (meth, n), (t, j) in thr.items():
                                arrays[f"{fr}|{meth}@{n}|{al}"] = t; summ[fr]["per_key_z"][f"{meth}@{n}|{al}"] = {"j": j, "z": R.zq(t, al)}
                            t_emp, kap, det = T.empirical_multiplier_threshold(Pf, al, beta); t_pool = T.pooled_threshold(Pf, al)
                            arrays[f"{fr}|empirical|{al}"] = np.array([t_emp]); arrays[f"{fr}|pooled|{al}"] = np.array([t_pool])
                            summ[fr]["scheme"][str(al)] = {"t_emp": t_emp, "kappa_emp": kap, "emp_detail": det, "t_pool": t_pool, "z_emp": float(norm.isf(t_emp)) if t_emp > 0 else None, "z_pool": float(norm.isf(t_pool)) if t_pool > 0 else None}
