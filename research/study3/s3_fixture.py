        res["FIXTURE"] = FIXTURE_NOTE
        (out_dir / "results.json").write_text(json.dumps(res, default=float, separators=(",", ":")))
        print(f"analysed the FIXTURE inventory in {time.time() - t0:.0f}s: T1 {res['T1']} T2 {res['T2']} REP {res['REP']}; {len(res['descriptive_rows'])} descriptive rows -> {out_dir / 'results.json'}")
