def sha(p):
    return hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()


def psd_cov(S):
    """The nearest PSD matrix by eigenvalue clipping (the fixture's cross-set covariances are interpolated, so the raw matrix may not be PSD)."""
    w, V = np.linalg.eigh((S + S.T) / 2); w = np.clip(w, 0.0, None)
    return (V * w) @ V.T


def shift_cov(blk, tok, cells):
    """Sigma over the 20 sets of one tokenizer (10 evaluation sets, then 10 calibration sets): rho_E and rho_C on the diagonal, the
    key-free rho_CE on the calibration-against-evaluation blocks, and the symmetrised rho_CE as a stand-in for the E-E and C-C blocks."""
    n = len(cells); S = np.zeros((2 * n, 2 * n)); ce = np.zeros((n, n))
    for i, tc in enumerate(cells):
        for j, te in enumerate(cells):
            ce[i, j] = blk["pairs"][f"{tok}|{tc}->{tok}|{te}"]["cross"]["5000"]["rho_CE"]
    for i, t in enumerate(cells):
        S[i, i] = blk["sets"][f"{tok}|{t}|E"]["rho"]; S[n + i, n + i] = blk["sets"][f"{tok}|{t}|C5000"]["rho"]
    for i in range(n):
        for j in range(n):
            S[n + i, j] = ce[i, j]; S[j, n + i] = ce[i, j]
            if i != j:
                S[i, j] = (ce[i, j] + ce[j, i]) / 2; S[n + i, n + j] = (ce[i, j] + ce[j, i]) / 2
    return psd_cov(S)


def planted_counts(mean, sd_total, N, K, rng):
    """Per-key counts whose level has (about) the given key-mean and total SD: a Gamma latent level plus binomial text noise."""
    mean = float(min(max(mean, 1e-6), 1 - 1e-6)); var_lat = max(sd_total ** 2 - mean * (1 - mean) / N, 1e-12)
    ell = np.clip(rng.gamma(mean ** 2 / var_lat, var_lat / mean, size=K), 0.0, 1.0)
    return rng.binomial(N, ell).astype(np.uint16)


def nest_alpha(arr, ia_new, new, alphas):
    """Replace the alpha slice ia_new (axis -2) with `new` and restore nesting across alpha (counts non-decreasing in alpha)."""
    order = np.argsort(alphas); arr[..., ia_new, :] = new
    pos = list(order).index(ia_new)
    for q in range(pos - 1, -1, -1):
        arr[..., order[q], :] = np.minimum(arr[..., order[q], :], arr[..., order[q + 1], :])
    for q in range(pos + 1, len(order)):
        arr[..., order[q], :] = np.maximum(arr[..., order[q], :], arr[..., order[q - 1], :])


def fake_interval(v, rng):
    lo = max(0.0, v * 0.9 - 0.0005); hi = min(1.0, v * 1.1 + 0.0005)
    return {"ci95": [float(lo), float(hi)], "boot_se": float((hi - lo) / 3.92)}


def fake_crossed(lv, a):
    """A crossed block with the registered fields built around the observed statistic (synthetic intervals; no resampling)."""
    st = {"q0.01": np.quantile(lv, 0.01), "q0.05": np.quantile(lv, 0.05), "q0.5": np.quantile(lv, 0.5), "q0.95": np.quantile(lv, 0.95), "q0.99": np.quantile(lv, 0.99),
          "max": lv.max(), "share2": np.mean(lv > 2 * a), "share5": np.mean(lv > 5 * a)}
    return {k: fake_interval(float(v), None) for k, v in st.items()} | {"B": 200, "note": "FIXTURE crossed block (synthetic intervals; no resampling)"}


def fake_cal_boot(lv, a, B, rng):
    base = {"key_mean": float(lv.mean()), "sd": float(lv.std(ddof=1)), "share_above_alpha": float(np.mean(lv > a)), "q99": float(np.quantile(lv, 0.99))}
    return {k: np.clip(v * (1 + 0.05 * rng.standard_normal(B)), 0.0, 1.0).tolist() for k, v in base.items()}


def s2_nominal(tok, tag, h, rule):
    """Study 2's recorded key-mean and SD of the KGW nominal level at alpha = 0.01 on the same texts (a finished study's record)."""
    p = S2_CELLS / f"{tag}__{tok}__kgw__h{h}__independent__g0.25__L256__{rule}.json"
    l = json.loads(p.read_text())["levels"]["0.01"]
    return float(l["key_mean_level"]), float(l["sd_obs_conditional"])


def main(a):
    out_dir = pathlib.Path(a[a.index("--out-dir") + 1]).resolve()
    if ROOT.resolve() in out_dir.parents or out_dir == ROOT.resolve():
        raise SystemExit("the fixture must be written outside the repository")
