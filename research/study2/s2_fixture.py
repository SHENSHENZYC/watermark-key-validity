def counts_nested(p_by_alpha, N, rng):
    """Nested binomial counts across alpha (non-decreasing in alpha for every key): the smaller alpha's count first, then the increment."""
    alphas = sorted(p_by_alpha); k = {}; prev_k = np.zeros_like(next(iter(p_by_alpha.values())), dtype=np.int64); prev_p = np.zeros_like(prev_k, dtype=np.float64)
    for a in alphas:
        p = np.maximum(p_by_alpha[a], prev_p); inc_p = np.clip((p - prev_p) / np.maximum(1 - prev_p, 1e-12), 0, 1); inc = rng.binomial(N - prev_k, inc_p); cur = prev_k + inc
        k[a] = cur; prev_k = cur; prev_p = p
    return k


def make_cell(c, L_list, grid, delta_tok, base_cell, rng, man, man_sha, lock_path):
    N = c["N"]; K = c["K"]; V = c["V"]; h = c["h"]; L = c["L"]; fam = c["family"]; indep = c["colouring"] == "independent"
    dep = in_deployer_subset(c, grid, L_list); M = mean_M(c); kk = key8(c)
    # the common-shift probit model: per-key shift delta_k shared across the cells of a tokenizer (correlations), scale s by width and length
    s = base_cell * F_H[h] * np.sqrt(M / 256.0) * (0.85 if c["rule"] == "distinct" else 1.0) * (0.7 if c["rule"] == "first" else 1.0)
    if (c["tag"], c["tokenizer"], h, c["rule"]) == PLANT["s4_fail"] and L == 256 and fam == "kgw" and c["gamma"] == 0.25 and indep:
        s *= 0.5
    if (c["tag"], c["tokenizer"], c["rule"]) == PLANT["s5_fail"] and h == 2 and L == max(L_list) and fam == "kgw" and c["gamma"] == 0.25 and indep:
        s *= 3.0
    d = 0.6 * delta_tok[c["tokenizer"]] + 0.8 * rng.standard_normal(K)
    sig2 = 1.0 + 0.6
    if c["rule"] == "raw":
        shift_mean = 1.0 * (1.0 if h == 0 else 0.4 / h)                 # the raw rule's inflated key mean (within-text repetition), largest at h = 0
    else:
        shift_mean = 0.0
    p_by_alpha = {}; exact = {}
    for a in grid["alpha"]:
        t = norm.isf(a) * np.sqrt(s ** 2 + sig2)
        p = norm.sf((t - s * d - shift_mean * np.sqrt(sig2)) / np.sqrt(sig2))
        p_by_alpha[a] = p; exact[a] = float(a)
    structural = fam == "kgw" and c["rule"] == "first" and h == 0
    if structural:                                                       # one token per text: no rejection at alpha <= 0.01 (gamma 0.25) or at any alpha (gamma 0.5)
        for a in grid["alpha"]:
            if c["gamma"] == 0.5 or a < 0.05:
                p_by_alpha[a] = np.zeros(K); exact[a] = 0.0
            else:
                p_by_alpha[a] = np.full(K, 0.25) + 0.02 * d; exact[a] = 0.25
    k = counts_nested(p_by_alpha, N, rng)
    factor = {a: 1.0 for a in grid["alpha"]}
    if kk == PLANT["s1_inconsistent"]:
        factor[0.01] = 0.5
    if kk == PLANT["s1_unresolved"]:
        factor[0.01] = 1.45
    if kk == PLANT["s2_flag"]:
        exact[0.05] = 0.2
    levels = {str(a): level_block(k[a], N, a, exact[a], factor[a], dep, rng, fam, indep) for a in grid["alpha"]}
    for a in grid["alpha"]:
        levels[str(a)]["pred_first_order"]["theory_share"] = THEORY_SHARE[h] + (0.25 if (h == 3 and c["tag"] in ("gutenberg_en_1024", "wikipedia_en_1024") and L >= 512) else 0.0)
        for kx in ("pred_unit_sigma", "pred_gaussian_shift_per_text", "pred_simulated_shift"):
            if kx in levels[str(a)]:
                levels[str(a)][kx]["theory_share"] = levels[str(a)]["pred_first_order"]["theory_share"]
    # the mean-score block (q_hat for KGW, s_bar for Gumbel) with the known-mean estimator against a fake exact identity
    g = c["gamma"] if fam == "kgw" else None; E = (g if fam == "kgw" else 1.0)
    A = 0.0058 * (0.5 ** h) * (256.0 / max(M, 1.0)) ** 0.3; exact_var = (g * (1 - g) * A) if fam == "kgw" else A
    if fam == "kgw" and c["colouring"] == "fixed":
        exact_var *= 0.9987
    vals = E + rng.standard_normal(K) * np.sqrt(exact_var)
    if kk == PLANT["s3_gross"]:
        vals = E + (vals - E) * np.sqrt(2.0)                              # the planted gross failure: the values themselves carry twice the exact variance
    s0 = float(((vals - E) ** 2).mean()); se = float(np.sqrt(2.0 / K) * exact_var)
    blk = {"mean": float(vals.mean()), "exact_mean": E, "var_across_keys": float(vals.var(ddof=1)), "var_boot_ci95": [s0 * 0.9, s0 * 1.1], "var_known_mean": s0, "var_known_mean_se": se,
           "se_method": "key bootstrap (empirical)" if c["colouring"] == "fixed" else ("exact fourth moment" if fam == "kgw" else "exact fourth moment (Exp(1) cumulant 6)"),
           "exact_var_own_colouring": exact_var, "r3_tolerance": 1e-9 * exact_var, "observed_sample_constancy": False, "structural_zero": False, "values": [round(float(v), 6) for v in vals]}
    C_cond = A / 1.0
    idq = ({"g": g, "m": c["m"], "A": A, "B": 1.0, "A4": A ** 2 * 0.14, "C_cond": C_cond, "var_fixed": exact_var * 0.9987, "var_indep": exact_var, "ratio_fixed_over_indep": (V - 1 / C_cond) / (V - 1), "exact_ratio_formula": (V - 1 / C_cond) / (V - 1), "degenerate": False, "structural_zero_fixed": False, "structural_zero_indep": False}
           if fam == "kgw" else {"A": A, "A4": A ** 2 * 0.14, "var": A, "structural_zero": False})
    rho = s ** 2 * 1.03; pop = {"rho_bar": rho, "rho_bar_boot_se": rho * 0.003, "A_q_between": A * 0.9999, "A_q_between_boot_se": A * 0.002, "var_zbar_exact_boot_se": rho * 0.003, "A_q_realised_boot_se": A * 0.002, "mean_var_text_z": 3.1, "mean_A_q_text": A * 2.1,
                               "mu_delta": 0.0, "sigma_model2": sig2, "var_zbar_exact": rho, "A_q_realised": A, "sd_zshift_pop": float(np.sqrt(rho)), "collision_h_analytic": None, "sigma_tol": 3.1e-9, "text_bootstrap_B": grid["text_bootstrap_B"]}
    het = {"n_subsample": 300, "pair_cov_mean": rho, "pair_cov_cv": 0.29, "pair_corr_quantiles": {"0.5": 0.48, "0.9": 0.59, "0.99": 0.66}, "pair_corr_max": 0.97, "share_zero_variance_texts": 0.0}
    het["replicate"] = dict(het, pair_cov_cv=0.28)
    d_out = {"g": g, "m": c["m"], "degenerate": False, "N": N, "levels": levels, "N_eff": N, "frac_M0": 0.0, "mean_M": M, "min_M": int(max(1, round(M * 0.8))), "max_M": int(round(M * 1.1)) if c["rule"] != "raw" else int(M),
             "M_quantiles": {"0.05": M * 0.9, "0.5": M, "0.95": M * 1.05}, "coverage": {"distinct_retained_tuples": int(50000 * (1 + h) * L / 256)},
             ("q_hat" if fam == "kgw" else "s_bar"): blk, "zbar": {"mean": 0.0, "var_across_keys": rho, "var_boot_ci95": [rho * 0.9, rho * 1.1]}, "z_var_within_key": {"mean_over_keys": sig2 + 0.09, "min": 1.3, "max": 2.4},
             "identity_q": idq, "identity_z": idq, "population": pop, "covariance_heterogeneity": het,
             "tag": c["tag"], "tokenizer": c["tokenizer"], "family": fam, "h": h, "L": L, "rule": c["rule"], "colouring": c["colouring"], "gamma": c["gamma"], "K": K, "V": V, "deployer_subset": bool(dep),
             "n_tuples_dict": int(50000 * (1 + h)), "n_contexts": 1 if h == 0 else int(40000 * h), "nnz": int(N * M), "seconds": 1.0, "FIXTURE": FIXTURE_NOTE}
    if h == 0:
        d_out["coverage"]["share_of_V_if_h0"] = 0.4
    if (fam == "kgw" and indep) or fam == "gumbel":
        d_out["simulated_shift"] = {"T": 2000, "B": 20000, "var_heavy_share": 0.999, "var_identity_realised": rho, "scale": 1.0, "sample_skew": 0.4, "sample_kurtosis_excess": -0.07}
    tokens_sha = man["cells"][c["tag"]]["tokenizers"][c["tokenizer"]]["sha256"]
    d_out["provenance"] = provenance("study", lock_path, GRID_CANON, tokens_sha, grid["key_seed_start"], K, N, slot_of(c), man_sha); d_out["provenance"]["written_utc"] = utc()
    return d_out


def main(a):
    out_dir = pathlib.Path(a[a.index("--out-dir") + 1]).resolve(); seed = int(a[a.index("--seed") + 1]) if "--seed" in a else 1
    if ROOT.resolve() in out_dir.parents or out_dir == ROOT.resolve():
        raise SystemExit("the fixture must be written outside the repository")
    out_dir.mkdir(parents=True, exist_ok=True)
    grid = json.loads((ROOT / GRID_CANON).read_text()); man = json.loads((ROOT / TOKENS_MANIFEST).read_text()); man_sha = sha(ROOT / TOKENS_MANIFEST); lock_path = ROOT / OUT / "PRE_RUN_LOCK.json"
    cells = expected_cells(grid); L_of = {sp["tag"]: sp["L"] for sp in grid["cells"]}
    rng0 = np.random.default_rng(seed); dl = rng0.standard_normal(grid["K"]); dq = 0.2 * dl + np.sqrt(1 - 0.04) * rng0.standard_normal(grid["K"])
    delta_tok = {"llama": dl, "qwen": dq}; base = {sp["tag"]: float(rng0.uniform(0.8, 1.2)) for sp in grid["cells"]}
    t0 = time.time(); n = 0
    for c in cells:
        rng = np.random.default_rng(int(hashlib.sha256(c["file"].encode()).hexdigest()[:8], 16) + seed)
        d = make_cell(c, L_of[c["tag"]], grid, delta_tok, base[c["tag"]], rng, man, man_sha, lock_path)
        (out_dir / c["file"]).write_text(json.dumps(d, default=float)); n += 1
        if n % 500 == 0:
            print(f"{n} cells ({time.time() - t0:.0f}s)", flush=True)
    (out_dir / "FIXTURE_README.txt").write_text(FIXTURE_NOTE + f"\nseed {seed}; {n} cells; planted: {json.dumps(PLANT)}\n")
    print(f"wrote {n} FIXTURE cells to {out_dir} in {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main(sys.argv[1:])
