def key8(c):
    return (c["tag"], c["tokenizer"], c["family"], c["h"], c["L"], c["rule"], c["colouring"], c["gamma"])


def mean_M(c):
    base = c["L"] - c["h"]
    if c["rule"] == "raw":
        return float(base)
    if c["rule"] == "distinct":
        return float(base) * (0.72 - 0.03 * c["h"])
    return 1.0 if c["h"] == 0 else float(base) * (0.45 - 0.02 * c["h"])


def boot_sd(lev, rng, B=200):
    K = len(lev); idx = rng.integers(0, K, size=(B, K)); s = lev[idx].std(axis=1, ddof=1)
    return [float(np.quantile(s, 0.025)), float(np.quantile(s, 0.975))], float(s.std(ddof=1))


def level_block(k, N, a, exact, sd_pred_factor, dep, rng, family, indep):
    lev = k / N; K = len(k); sd = float(lev.std(ddof=1)); ci, se = boot_sd(lev, rng)
    sd_pred = sd * sd_pred_factor if sd > 0 else 0.0
    pbound = C.kl_chernoff_pbound(float(lev.mean()), float(exact), K)
    pred = {"mean_level": float(lev.mean()) * 0.98, "var_pop": sd_pred ** 2, "sd_pop": sd_pred, "floor": a * (1 - a) / N, "sd_cond": sd_pred, "theory_share": None, "sd_linear_pop": sd_pred * 0.6, "sigma2": 1.6, "flags": []}
    lv = {"key_mean_level": float(lev.mean()), "unconditional_rate": float(lev.mean()), "se_conditional_on_texts": float(lev.std(ddof=1) / np.sqrt(K)), "r2_kl_pbound": pbound,
          "pred_pairwise_gaussian": {"sd_cond": sd_pred * 1.02, "var_signed": (sd_pred * 1.02) ** 2, "mean_level": float(lev.mean()) * 0.99, "floor_part": a * (1 - a) / N, "offdiag_part": (sd_pred * 1.02) ** 2, "sd_cond_replicate": sd_pred * 0.99, "subsample_sd_difference": sd_pred * 0.03},
          "sd_obs_conditional": sd, "sd_obs_boot_ci95": ci, "sd_obs_boot_se": se, "pred_first_order": pred,
          "pred_unit_sigma": dict(pred, sd_cond=sd_pred * 0.95, sd_pop=sd_pred * 0.95, var_pop=(sd_pred * 0.95) ** 2, sigma2=1.0),
          "ratio_obs_over_pred": (sd / sd_pred) if sd_pred > 0 else float("nan"), "ratio_boot_ci95": [ci[0] / sd_pred, ci[1] / sd_pred] if sd_pred > 0 else [float("nan"), float("nan")], "ratio_boot_se": (se / sd_pred) if sd_pred > 0 else float("nan"),
          "population_est": {"s_K2": sd ** 2, "MS_E": float(lev.mean()) * (1 - float(lev.mean())), "var_pop_signed": sd ** 2 - float(lev.mean()) * (1 - float(lev.mean())) / N, "sd_pop": sd, "var_pop_boot_se": sd ** 2 * 0.1, "var_pop_boot_mean": sd ** 2, "var_pop_ci95_normal": [sd ** 2 * 0.8, sd ** 2 * 1.2]},
          "quantiles": {q: float(np.quantile(lev, float(q))) for q in QUANTILE_KEYS}, "max_key": float(lev.max()), "min_key": float(lev.min()),
          "share_keys_above_2alpha": float(np.mean(lev > 2 * a)), "share_keys_above_5alpha": float(np.mean(lev > 5 * a)), "structural_zero": bool(lev.max() == 0.0 and exact == 0.0), "level_counts": [int(x) for x in k]}
    if family == "kgw":
        lv["exact_marginal_if_indep_distinct"] = float(exact)
    else:
        lv["exact_marginal_if_distinct"] = float(exact); lv.update({"threshold_z_mean": 2.4, "threshold_z_min": 2.3, "threshold_z_max": 2.5}); pred.update({"shift_sd": 1.2, "n_distinct_thresholds": 3, "method": "closed form (Owen's T over distinct thresholds)"})
    if family == "kgw" and indep:
        lv["pred_gaussian_shift_per_text"] = dict(pred, shift_sd=1.2, n_distinct_thresholds=1, method="closed form (Owen's T over distinct thresholds)"); lv["pred_per_text_vs_closed_form_abs_diff_sd"] = 0.0
    if (family == "kgw" and indep) or family == "gumbel":
        lv["pred_simulated_shift"] = dict(pred, sd_cond=sd_pred * 1.05, sd_pop=sd_pred * 1.05, var_pop=(sd_pred * 1.05) ** 2, shift_sd=1.21, n_distinct_thresholds=1); lv["ratio_obs_over_pred_simulated_shift"] = (sd / (sd_pred * 1.05)) if sd_pred > 0 else float("nan")
    if dep:
        cr = {}
        for kk, v in (("q0.01", lv["quantiles"]["0.01"]), ("q0.05", lv["quantiles"]["0.05"]), ("q0.5", lv["quantiles"]["0.5"]), ("q0.95", lv["quantiles"]["0.95"]), ("q0.99", lv["quantiles"]["0.99"]), ("max", lv["max_key"]), ("share2", lv["share_keys_above_2alpha"]), ("share5", lv["share_keys_above_5alpha"])):
            lo = max(0.0, v * 0.9 - 0.0005); hi = min(1.0, v * 1.1 + 0.0005); cr[kk] = {"ci95": [lo, hi], "boot_se": (hi - lo) / 3.92}
        cr["B"] = CROSSED_B; cr["note"] = "FIXTURE crossed block (synthetic intervals)"; lv["deployer_crossed"] = cr
