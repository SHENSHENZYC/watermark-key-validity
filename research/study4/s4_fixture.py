"""Study 4 synthetic fixture (NOT an outcome). Writes a complete fake inventory of the production grid in the run's exact file layout
(the 30 null units of 500 texts and the 900 generation units of 50 texts, with the provenance of the lock, the grid, the code and the
manifests) into a directory OUTSIDE the repository, so that the report builder can be exercised on the real results.json format before
any outcome exists (the practice of Studies 2 and 3). No model is loaded: the tokens are random draws over the vocabulary; in a generation
unit the share of green tokens per text is PLANTED (a per-text target z-score under the raw rule, from a planted law with key, prompt and
noise components) by rejection-sampling candidates against the LOCKED hash's colouring, so the stored flags equal the detector's at every
scored position and the locked analyzer's hook-flag contract passes; one unit carries a flipped flag (a contract failure), one unit carries
looping texts (rep-4 above the bar), the quality arrays are fake. The planted law per prompt cell at the primary arm: news with its median
cost at the pilot-law prediction (W1 consistent), Wikipedia at the prediction minus the tolerance minus 8 pp (W1 inconsistent), Stack
Exchange at the band's lower edge (W1 unresolved) with the key's null shift entering with a negative sign (a raw-rule W2 disagreement);
the key effect of the other cells is the key's own calibrated null shift plus an independent strength term (a raw-rule W2 agreement). The
null units are uniform random tokens (W3's rows fall where they fall). Every unit record carries a top-level FIXTURE marker. The LOCKED
analyzer refuses such a record in study mode (correctly), so `--analyze` runs it on a transient copy of the cells with the marker stripped,
marks the output results.json with the same note, and deletes the copy; the builder requires the marker in fixture mode and refuses it in
study mode. No Study 4 outcome is read; no statistic of this fixture means anything.
Usage: .venv/bin/python research/study4/s4_fixture.py --out-dir <directory outside the repository> [--seed 1]
       .venv/bin/python research/study4/s4_fixture.py --out-dir <the same directory> --analyze
"""
import hashlib, json, os, pathlib, shutil, sys, time
import numpy as np
from scipy.stats import norm
HERE = pathlib.Path(__file__).resolve().parent; ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE)); sys.path.insert(0, str(ROOT / "research/study1")); sys.path.insert(0, str(ROOT / "research/study2")); sys.path.insert(0, str(ROOT / "research/study3"))
os.chdir(ROOT)
import s4_run as R, s4_wm as W, s4_core as T4, s4_record as RC, s4_analyze as A
import s1_core as C

FIXTURE_NOTE = ("synthetic fixture generated by research/study4/s4_fixture.py; NOT an outcome of Study 4; no text was generated by the model; the tokens are random "
                "draws with a planted share of the detector's green tokens; every number is planted")
PLANT = {"w1_consistent": "news_en_256", "w1_inconsistent": "wikipedia_en_256", "w1_unresolved_and_w2_raw_disagree": "stackexchange_en_256",
         "contract_failure_unit": ("news_en_256", "kgw_h1_d2.0", 3), "loop_unit": ("wikipedia_en_256", "kgw_h1_d0.5", 7), "w1_inconsistent_offset_pp": 8.0}
SIG_B, SIG_C, SIG_W = 0.30, 0.80, 0.30     # the planted prompt effect, the cell noise (the pilot's within-key spread is about 1.1 z) and the key-strength term (z units)
MU_SATURATED = 5.0                          # the delta = 2.0 arm
V_TOKENS = 151_000                          # the fixture samples token ids uniformly below this (inside [0, V); the special and padding ids lie above)


def sha(p):
    return hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()


def key_shift(cu, rule, key, alpha, N_cal):
    """The key's calibrated null shift D_k = z(t_k) - z(alpha) under the record's conformal threshold (0 threshold: an abstaining key, +inf)."""
    t = float(cu.threshold("kgw", rule, "conformal", alpha, N_cal)[key - 23000])
    return (float(norm.isf(t)) - float(norm.isf(alpha))) if t > 0 else float("inf")


def z_realised(z, g, M):
    """The z the detector will compute from the planted integer green count (the fixture's rounding is exact)."""
    G = np.clip(np.rint(g * M + z * np.sqrt(M * g * (1 - g))), 0, M); return (G - g * M) / np.sqrt(M * g * (1 - g))


def realised_median_cost(mu, zc, z_alpha, z_t, g, M):
    """The key-median of the realised cost over the planted draws zc (K x n, without mu): 1{z > z_alpha} - 1{z > z(t_k)} averaged over prompts."""
    zr = z_realised(mu + zc, g, M); return float(np.median((zr > z_alpha).mean(axis=1) - (zr > z_t[:, None]).mean(axis=1)))


def find_mu_realised(target, zc, z_alpha, z_t, g, M, pilot_power, branch=None):
    """The mu whose realised key-median cost is closest to the target, on whichever branch of the unimodal cost curve (rising: low power; falling:
    high power) puts the key-mean nominal power closest to the pilot's nominal power for the cell (so the fixture sits in the pilot's regime)."""
    grid_mu = np.linspace(-2.0, 6.0, 801); med = np.array([realised_median_cost(m, zc, z_alpha, z_t, g, M) for m in grid_mu]); i_peak = int(np.argmax(med))
    cands = []
    for lo, hi in ((0, i_peak + 1), (i_peak, len(grid_mu))):
        j = int(np.argmin(np.abs(med[lo:hi] - target))) + lo; pw = float((z_realised(grid_mu[j] + zc, g, M) > z_alpha).mean()); cands.append((abs(pw - pilot_power), abs(med[j] - target), j, pw))
    if branch == "high":      # the sign-flipped cell: the high-power branch, where the flipped null shift makes the conformal table more dispersed than the nominal (a raw-rule disagreement)
        j = cands[1][2] if cands[1][3] > cands[0][3] else cands[0][2]
    else:
        cands.sort(); j = cands[0][2]
    return float(grid_mu[j]), float(med[j]), float(med[i_peak])


def gen_unit_tokens(rng, key, h, z_target, n_new, g, V):
    """Tokens (n x n_new int32) whose green count at the scored positions (t >= h) is the planted count per text, with the colour of every
    chosen token decided by the LOCKED hash (the detector's colouring at the context of the previous h generated tokens); the flags."""
    n = len(z_target); M = n_new - h; G = np.clip(np.rint(g * M + z_target * np.sqrt(M * g * (1 - g))), 0, M).astype(int)
    X = np.zeros((n, n_new), dtype=np.int32); flag = np.zeros((n, n_new), dtype=np.uint8)
    want = np.zeros((n, n_new), dtype=bool)
    for i in range(n):
        pos = rng.permutation(M)[: G[i]] + h; want[i, pos] = True
    X[:, :h] = rng.integers(0, V_TOKENS, size=(n, h))
    for t in range(h, n_new):
        cids = W.context_hash_batch(X[:, :t], h) if h > 0 else np.zeros(n, dtype=np.uint64)
        todo = np.ones(n, dtype=bool); v = np.zeros(n, dtype=np.int64)
        for _ in range(200):
            idx = np.flatnonzero(todo)
            if idx.size == 0:
                break
            cand = rng.integers(0, V_TOKENS, size=idx.size)
            with np.errstate(over="ignore"):
                tids = C.mix64(cids[idx] * C.C2 + (cand.astype(np.uint64) + np.uint64(1)) * C.C1)
            green = C.uniforms(key, tids) < g
            ok = green == want[idx, t]; v[idx[ok]] = cand[ok]; todo[idx[ok]] = False
        if todo.any():   # a candidate of the wanted colour not found in 200 draws (vanishingly rare): take the last candidates as they are
            v[todo] = cand[-todo.sum():] if cand.size >= todo.sum() else rng.integers(0, V_TOKENS, size=todo.sum()); want[todo, t] = False
        X[:, t] = v; flag[:, t] = want[:, t]
    return X, flag


def fake_quality(rng, X):
    n, L = X.shape
    logp = (-(3.0 + 0.5 * rng.standard_normal((n, L)))).astype(np.float32); logp = np.minimum(logp, -1e-3).astype(np.float32)
    eos = (rng.uniform(0.0, 0.05, size=(n, L))).astype(np.float16)
    return logp, eos


def write_unit(cells, u, name, arrays, prov, rng, note=FIXTURE_NOTE):
    npz = cells / f"{name}.npz"; np.savez_compressed(npz, **arrays); tokens = arrays["tokens"]
    secs = float(rng.uniform(30, 45)) if u["kind"] == "gen" else float(rng.uniform(240, 280))
    rec = {"FIXTURE": note, "unit": u, "name": name, "n": int(tokens.shape[0]), "n_new": int(tokens.shape[1]), "npz_sha256": sha(npz), "seconds": round(secs, 1), "tok_per_s": round(tokens.size / secs, 1),
           "seconds_model": round(0.7 * secs, 1), "seconds_hook": round(0.25 * secs, 1), "cache_hits": int(rng.integers(0, 3000)), "cache_misses": int(rng.integers(9000, 12000)),
           "green_share_hook": float(arrays["flag"].mean()) if "flag" in arrays else None, "mean_logp": float(arrays["logp"].mean()), "eos_mass_mean": float(arrays["eos_mass"].astype(np.float32).mean()),
           "peak_rss_gb": 2.92, "provenance": dict(prov, written_utc=R.utc())}
    (cells / f"{name}.json").write_text(json.dumps(rec, indent=0))


def main(a):
    out_dir = pathlib.Path(a[a.index("--out-dir") + 1]).resolve()
    if ROOT.resolve() in out_dir.parents or out_dir == ROOT.resolve():
        raise SystemExit("the fixture must be written outside the repository")
    grid = json.loads((ROOT / R.GRID_CANON).read_text()); lock_path = R.OUT / "PRE_RUN_LOCK.json"
    if not lock_path.exists():
        raise SystemExit("no lock: the fixture carries the lock's digest in its provenance")
    if "--analyze" in a:
        cells = out_dir / "cells"
        if not cells.exists():
            raise SystemExit(f"no fixture cells at {cells}")
        stripped = out_dir / "cells_marker_stripped_transient"
        if stripped.exists():
            shutil.rmtree(stripped)
        shutil.copytree(cells, stripped); n_str = 0
        for jp in stripped.glob("*.json"):
            rec = json.loads(jp.read_text())
            if "FIXTURE" not in rec:
                raise SystemExit(f"{jp.name}: a fixture record without the FIXTURE marker; refusing")
            rec.pop("FIXTURE"); jp.write_text(json.dumps(rec, indent=0)); n_str += 1
        inputs = json.loads((R.OUT / "INPUTS.json").read_text()); inputs["_sha256"] = sha(R.OUT / "INPUTS.json")
        t0 = time.time(); out, arrays = A.analyze(grid, stripped, inputs, "study", lock_path=str(lock_path), log=lambda m: print(m, flush=True))
        out["FIXTURE"] = FIXTURE_NOTE; out["label"] = "FIXTURE (synthetic inventory; not the study)"; out["fixture_cells_dir"] = str(cells)
        np.savez_compressed(out_dir / "results_arrays.npz", **arrays); out["arrays_sha256"] = sha(out_dir / "results_arrays.npz")
        (out_dir / "results.json").write_text(json.dumps(out, indent=0, default=float)); shutil.rmtree(stripped)
        print(f"analysed the FIXTURE inventory ({n_str} records, marker stripped on the transient copy) in {time.time() - t0:.0f}s: W1 {out['W1'].get('pass')} W2 {out['W2'].get('pass')} W3 {out['W3'].get('pass')}; "
              f"contract failures {out['integrity']['n_contract_failures']}; {len(out['descriptive_rows'])} descriptive rows, {len(out['null_rows'])} null rows -> {out_dir / 'results.json'}")
        return
    seed = int(a[a.index("--seed") + 1]) if "--seed" in a else 1
    cells = out_dir / "cells"; cells.mkdir(parents=True, exist_ok=True)
    for f in cells.iterdir():
        f.unlink()
    lock_sha = sha(lock_path); grid_sha = sha(ROOT / R.GRID_CANON); pm = json.loads((ROOT / grid["prompts"]["manifest"]).read_text()); pm_sha = sha(ROOT / grid["prompts"]["manifest"])
    model_man = json.loads((ROOT / grid["model"]["weights_manifest"]).read_text()); code = {f: sha(HERE / f) for f in ("s4_gen.py", "s4_wm.py", "s4_run.py", "s4_data.py", "s4_keys.py", "s4_record.py")}
    V = grid["model"]["V"]; gamma = grid["gamma"]; g = C.green_fraction(gamma, V); n_new = grid["generation"]["n_new"]; alpha = float(grid["W1"]["alpha"]); z_alpha = float(norm.isf(alpha))
    keys = grid["keys"]["power_keys"]; Rrec = RC.Record(verify_files=False); inputs = json.loads((R.OUT / "INPUTS.json").read_text())
    rng0 = np.random.default_rng(seed); t_all = time.time(); n_written = 0; planted = {}
    units = R.expected_units(grid, False)
    # the planted laws per cell and arm: the draws first (the prompt effects shared by every key and arm of a cell; the key-strength term; the cell noise per arm), then the
    # primary arm's mu solved on the REALISED draws for the W1 target (the realised prompt sample shifts every key's rejection share together, so a normal-model search misses
    # by several pp), then the classes the analyzer will find computed from the planted integer green counts with the analyzer's own rule functions
    n_tx = grid["prompts"]["n_watermarked"]; M = n_new - 1; z_alpha_v = z_alpha
    b_prompt = {cell: rng0.normal(0, SIG_B, size=n_tx) for cell in grid["cells"]}; w_key = {cell: rng0.normal(0, SIG_W, size=len(keys)) for cell in grid["cells"]}
    c_noise = {(cell, arm["name"]): rng0.normal(0, SIG_C, size=(len(keys), n_tx)) for cell in grid["cells"] for arm in grid["arms"]}
    mu = {}; w1_set = grid["W1"]; w2_set = grid["W2"]
    for cell in grid["cells"]:
        cu1 = Rrec.cal("qwen", cell, 1); D1 = np.array([key_shift(cu1, "raw", k, alpha, w1_set["N_cal"]) for k in keys]); z_t1 = z_alpha + D1
        sign = -1.0 if cell == PLANT["w1_unresolved_and_w2_raw_disagree"] else 1.0; a_k = sign * D1 + w_key[cell]
        law = T4.PooledLaw(np.array(inputs["pilot_law"]["arms"][w1_set["arm"]]["by_cell"][cell]["p_values"][f"raw@{n_new}"]))
        t_keys = np.array([float(cu1.threshold("kgw", "raw", "conformal", alpha, w1_set["N_cal"])[k - 23000]) for k in keys]); pred = law.predicted_cost(t_keys, alpha); pred_med = float(np.median(pred))
        tol = float(inputs["W1_tolerance"][cell]["tolerance_pp"]) / 100
        target = {PLANT["w1_consistent"]: pred_med, PLANT["w1_inconsistent"]: pred_med - tol - PLANT["w1_inconsistent_offset_pp"] / 100, PLANT["w1_unresolved_and_w2_raw_disagree"]: pred_med - tol}[cell]
        zc = a_k[:, None] + b_prompt[cell][None, :] + c_noise[(cell, w1_set["arm"])]
        pilot_power = float(inputs["pilot_law"]["arms"][w1_set["arm"]]["by_cell"][cell]["z"][f"raw@{n_new}"]["power_nominal_0.01"])
        m1, achieved, peak = find_mu_realised(max(target, 0.005), zc, z_alpha, z_t1, g, M, pilot_power, branch=("high" if sign < 0 else None))
        zr = z_realised(m1 + zc, g, M); real = (zr > z_alpha).mean(axis=1) - (zr > z_t1[:, None]).mean(axis=1)
        w1c = A.w1_row(cell, real, pred, (zr > z_alpha).mean(axis=1), dict(w1_set, tolerance_pp=100 * tol), law.n)
        w2c = {}
        for rule in grid["rules"]:
            cu_r = Rrec.cal("qwen", cell, 1); t_c = np.array([float(cu_r.threshold("kgw", rule, w2_set["method"], float(w2_set["alpha"]), w2_set["N_cal"])[k - 23000]) for k in keys])
            Yn = (norm.sf(zr) < float(w2_set["alpha"])).astype(float); Yc = (norm.sf(zr) < t_c[:, None]).astype(float); r2 = A.w2_row(cell, rule, Yn, Yc, w2_set); w2c[rule] = {"class": r2["class"], "R": round(r2["R_pow"], 3), "ci": [round(r2["ci_lo"], 3), round(r2["ci_hi"], 3)]}
        cu2 = Rrec.cal("qwen", cell, 2); D2 = np.array([key_shift(cu2, "raw", k, alpha, w1_set["N_cal"]) for k in keys])
        mu[cell] = {"kgw_h1_d0.5": (m1, a_k), "kgw_h1_d2.0": (MU_SATURATED, a_k), "kgw_h2_d0.5": (m1, sign * D2 + w_key[cell])}
        planted[cell] = {"predicted_median_cost": pred_med, "tolerance": tol, "target_median_cost": target, "mu_primary": m1, "realised_median_cost_at_mu": achieved, "peak_median_cost": peak, "key_shift_sign": sign, "pilot_nominal_power": pilot_power,
                         "sd_D_raw_h1": float(np.std(D1[np.isfinite(D1)], ddof=1)), "n_abstaining_h1": int((~np.isfinite(D1)).sum()), "W1_class_expected": w1c["class"], "W1_ci_expected": [round(w1c["ci_lo"], 3), round(w1c["ci_hi"], 3)],
                         "nominal_power_expected": round(float((zr > z_alpha).mean()), 3), "W2_expected": w2c}
    print("planted laws:", json.dumps(planted, default=float), flush=True)
    for u in units:
        name = R.unit_name(u); prov = R.provenance("study", lock_sha, grid, grid_sha, pm_sha, pm["cells"][u["cell"]]["kinds"]["prod"]["sha256"], model_man, code, u, "prod")
        rng = np.random.default_rng([R.unit_seed(name), seed, 7])
        if u["kind"] == "null":
            X = rng.integers(0, V_TOKENS, size=(u["n"], n_new)).astype(np.int32); logp, eos = fake_quality(rng, X)
            write_unit(cells, u, name, {"tokens": X, "logp": logp, "eos_mass": eos}, prov, rng); n_written += 1
            continue
        arm = R.arm_spec(grid, u["arm"]); ik = keys.index(u["key"]); m_, a_k = mu[u["cell"]][u["arm"]]
        z = m_ + a_k[ik] + b_prompt[u["cell"]] + c_noise[(u["cell"], u["arm"])][ik]
        X, flag = gen_unit_tokens(rng, u["key"], arm["h"], z, n_new, g, V)
        if (u["cell"], u["arm"], ik) == PLANT["loop_unit"]:
            for i in range(8):
                X[i, 96:] = np.tile(X[i, 96:100], 40)   # 160 looping tokens: rep-4 about 0.6, above the loop bar
            det, valid = T4.detector_green_flags(T4.score_set(X, V, arm["h"], [u["key"]], gamma, ("raw",), (n_new,))[3], u["key"], gamma, V); flag = np.where(valid, det, 0).astype(np.uint8)
        det, valid = T4.detector_green_flags(T4.score_set(X, V, arm["h"], [u["key"]], gamma, ("raw",), (n_new,))[3], u["key"], gamma, V)
        if not np.array_equal(det[valid], flag[valid].astype(bool)):
            raise RuntimeError(f"{name}: the planted flags differ from the detector's colouring")
        if (u["cell"], u["arm"], ik) == PLANT["contract_failure_unit"]:
            flag[0, 10] = 1 - flag[0, 10]
        logp, eos = fake_quality(rng, X)
        write_unit(cells, u, name, {"tokens": X, "logp": logp, "eos_mass": eos, "flag": flag}, prov, rng); n_written += 1
        if n_written % 100 == 0:
            print(f"  {n_written} units ({time.time() - t_all:.0f}s)", flush=True)
    (out_dir / "FIXTURE_README.txt").write_text(FIXTURE_NOTE + f"\nseed {seed}; {n_written} units; planted: {json.dumps(PLANT)}\nlaws: {json.dumps(planted)}\n")
    print(f"wrote {n_written} FIXTURE units to {cells} in {time.time() - t_all:.0f}s")


if __name__ == "__main__":
    main(sys.argv[1:])
