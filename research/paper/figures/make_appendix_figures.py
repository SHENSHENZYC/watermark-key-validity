#!/usr/bin/env python3
"""The Appendix D figures D1–D5: the agreed reports' own figures, copied with their provenance (guide A4.1, A4.10).

Each is generated by the study's report builder from the locked record (byte-reproducible builds; viewed and agreed at
the report's checkpoint) and is copied here unchanged, PNG and SVG, so that the paper is self-contained; the source
path, the report's figure number and the SHA-256 of every copied file are written to
``figures/appendix_figures_provenance.json``. Figures D6 and D7 are generated by the main figures' scripts
(``fig1_deployer.py``, ``fig5_transfer.py``) and are not touched here.

Usage:  .venv/bin/python research/paper/figures/make_appendix_figures.py
"""
from __future__ import annotations

import hashlib
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paperlib as P  # noqa: E402

FIGS = [  # (paper name, study, report file stem, the report's figure number, what it shows)
    ("figD1_keys_length", "s1", "fig4_keys", 4, "the distribution of per-key levels over the keys against length (one law, three rules)"),
    ("figD2_breakeven", "s3", "fig4_breakeven", 4, "the break-even calibration size on the diagonal"),
    ("figD3_w1_costs", "s4", "fig2_w1_costs", 1, "W1: the realised cost per key against the threshold-shift prediction"),
    ("figD4_power_length", "s4", "fig4_length", 5, "power against length at the primary arm"),
    ("figD5_zcost", "s3", "fig5_zcost", 5, "the null-side cost in z of each method"),
]


def main() -> int:
    out = P.PAPER / "figures"; prov = {}
    for name, s, stem, n, what in FIGS:
        src_dir = P.ROOT / P.STUDY_DIR[s] / "report"
        entry = {"study": P.STUDY_NAME[s], "report_figure": n, "what": what, "checkpoint": P.CHECKPOINT_OF_REPORT[s], "files": {}}
        for ext in ("png", "svg"):
            src = src_dir / f"{stem}.{ext}"; dst = out / f"{name}.{ext}"
            assert src.exists(), src
            shutil.copyfile(src, dst)
            entry["files"][ext] = {"source": str(src.relative_to(P.ROOT)), "sha256": hashlib.sha256(dst.read_bytes()).hexdigest(), "bytes": dst.stat().st_size}
            assert entry["files"][ext]["sha256"] == hashlib.sha256(src.read_bytes()).hexdigest()
        prov[name] = entry
        print(f"copied {entry['files']['png']['source']} -> figures/{name}.png (+svg)")
    (out / "appendix_figures_provenance.json").write_text(json.dumps(prov, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote figures/appendix_figures_provenance.json ({len(prov)} figures)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
